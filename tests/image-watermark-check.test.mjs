import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, basename, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { inspectImageWatermark } from '../server/image-watermark-check.mjs';

// A real tiny PNG keeps mock OCR tests independent of platform codecs.
const image = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j1ioAAAAASUVORK5CYII=';
const line = (text, x = 740, y = 760, width = 240, height = 25) => ({ text, x, y, width, height });
const response = lines => ({ status: 'ok', language: 'zh-Hans-CN', width: 1000, height: 800, lines });

test('OCR recognizes only compact standalone AI labels near image edges, with normalized positions', async () => {
  for (const label of ['AI 生成', 'A 丨 生 成', '内容由AI生成', '人工智能生成', 'AI generated', 'Generated by AI', 'AIGC']) {
    const value = await inspectImageWatermark(image, { runner: async () => response([line(label)]) });
    assert.equal(value.status, 'detected', label);
    assert.deepEqual(value.regions, [{ text: label, x: .74, y: .95, width: .24, height: .03125 }]);
    assert.equal(value.width, 1000); assert.equal(value.height, 800);
    assert.match(value.engine, /本机/); assert.match(value.message, /可能有误或漏检/);
    assert.ok(Number.isFinite(Date.parse(value.checkedAt)));
  }
});

test('promotional copy mentioning AI, central labels, and large headings are not watermark detections', async () => {
  const value = await inspectImageWatermark(image, { runner: async () => response([
    line('这门课程教你用AI生成产品图片', 20, 750, 700, 30),
    line('Try AI generated designs for your product', 20, 40, 700, 25),
    line('AI生成', 420, 380, 160, 30),
    line('AI generated', 20, 20, 600, 80),
    line('AI助理', 800, 770, 120, 24),
  ]) });
  assert.equal(value.status, 'not_detected'); assert.deepEqual(value.regions, []);
  assert.match(value.message, /不代表图片没有水印或 AI 标识/);
});

test('invalid media and extreme image dimensions never launch OCR', async () => {
  let calls = 0;
  const oversized = Buffer.from(image.split(',')[1], 'base64'); oversized.writeUInt32BE(30000, 16);
  for (const data of [null, '', 'https://example.invalid/image.png', 'data:image/svg+xml;base64,PHN2Zy8+', 'data:image/png;base64,iVBORw0KGgo=', 'data:image/jpeg;base64,/9j/4AAESkb/2Q==', image + 'private', `data:image/png;base64,${oversized.toString('base64')}`]) {
    const value = await inspectImageWatermark(data, { runner: async () => { calls++; return response([]); } });
    assert.equal(value.status, 'unavailable');
  }
  assert.equal(calls, 0);
});

test('missing Chinese OCR, unrecognizable text and malformed results report unavailable', async () => {
  for (const raw of [
    { status: 'unavailable', reason: 'chinese_unavailable' },
    { ...response([line('AI generated')]), language: 'en-US' },
    response([]), response([line('')]),
    { ...response([line('AI生成')]), width: NaN },
    { status: 'ok', width: 1000, height: 800, language: 'zh-Hans-CN', lines: null },
  ]) {
    const value = await inspectImageWatermark(image, { runner: async () => raw });
    assert.equal(value.status, 'unavailable'); assert.deepEqual(value.regions, []);
  }
});

test('image exists only in a random OS temporary directory and is removed on success, failure and timeout', async () => {
  for (const behavior of ['success', 'throw', 'timeout']) {
    let path;
    const value = await inspectImageWatermark(image, { timeoutMs: 50, runner: async ({ imagePath, signal }) => {
      path = imagePath;
      assert.equal(dirname(dirname(path)), resolve(tmpdir()));
      assert.match(basename(dirname(path)), /^shengzhang-image-ocr-/);
      assert.deepEqual(readFileSync(path), Buffer.from(image.split(',')[1], 'base64'));
      if (behavior === 'throw') throw Error('PRIVATE_TEXT C:\\Users\\private\\image.png');
      if (behavior === 'timeout') return new Promise(accept => signal.addEventListener('abort', () => accept({ status: 'unavailable', reason: 'timeout' }), { once: true }));
      return response([line('AI生成')]);
    } });
    assert.ok(path); assert.equal(existsSync(path), false); assert.equal(existsSync(dirname(path)), false);
    assert.equal(value.status, behavior === 'success' ? 'detected' : 'unavailable');
    assert.doesNotMatch(JSON.stringify(value), /PRIVATE_TEXT|C:\\\\Users/);
    if (behavior === 'timeout') assert.match(value.message, /超时/);
  }
});

test('out-of-bounds OCR coordinates cannot create unsafe overlay regions', async () => {
  const value = await inspectImageWatermark(image, { runner: async () => response([
    line('AI生成', -3), line('AI生成', 990), line('AI生成', 740, Infinity),
    line('AI生成', 740, 760, -3), line('AI生成', 740, 760, 240, NaN),
  ]) });
  assert.equal(value.status, 'unavailable'); assert.deepEqual(value.regions, []);
});

test('Windows OCR reads synthetic Chinese and English corner labels and excludes promotional sentences', { skip: process.platform !== 'win32' }, async t => {
  const executable = resolve(process.env.SystemRoot || 'C:/Windows', 'System32/WindowsPowerShell/v1.0/powershell.exe');
  for (const [label, x, expected] of [['AI generated', 760, 'detected'], ['AI生成', 820, 'detected'], ['课程教你用AI生成产品图片', 20, 'not_detected']]) {
    const script = `Add-Type -AssemblyName System.Drawing
  $image = New-Object System.Drawing.Bitmap(1000,800)
  $graphics = [System.Drawing.Graphics]::FromImage($image)
  $font = New-Object System.Drawing.Font('Microsoft YaHei',24)
  $stream = New-Object System.IO.MemoryStream
  try {
    $graphics.Clear([System.Drawing.Color]::White)
    $graphics.DrawString('Synthetic product picture',$font,[System.Drawing.Brushes]::Black,240,350)
    $graphics.DrawString('${label}',$font,[System.Drawing.Brushes]::Black,${x},750)
    $image.Save($stream,[System.Drawing.Imaging.ImageFormat]::Png)
    [Console]::Out.Write([Convert]::ToBase64String($stream.ToArray()))
  } finally { $stream.Dispose(); $font.Dispose(); $graphics.Dispose(); $image.Dispose() }`;
    const encoded = execFileSync(executable, ['-NoProfile', '-NonInteractive', '-Command', script], { windowsHide: true, encoding: 'utf8', timeout: 10000, maxBuffer: 1024 * 1024 });
    const value = await inspectImageWatermark(`data:image/png;base64,${encoded}`);
    if (value.status === 'unavailable' && /未安装/.test(value.message)) return t.skip('Windows Chinese OCR recognizer is not installed');
    assert.equal(value.status, expected, JSON.stringify(value));
    if (expected === 'detected') {
      assert.ok(value.regions.some(region => /A\s*[I1l丨]\s*(generated|生\s*成)/i.test(region.text)));
      assert.ok(value.regions.every(region => region.x > .7 && region.y > .9));
    }
  }
});
